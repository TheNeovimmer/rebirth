<script>
  var header = document.getElementById('header');
  var navToggle = document.getElementById('navToggle');
  var navLinks = document.getElementById('navLinks');
  navToggle.addEventListener('click', function () {
    var isOpen = navLinks.classList.toggle('open');
    navToggle.classList.toggle('active');
    navToggle.setAttribute('aria-expanded', isOpen);
  });
  document.querySelectorAll('.nav-links a').forEach(function (link) {
    link.addEventListener('click', function () {
      navLinks.classList.remove('open');
      navToggle.classList.remove('active');
      navToggle.setAttribute('aria-expanded', 'false');
    });
  });
  window.addEventListener('scroll', function () {
    header.classList.toggle('scrolled', window.pageYOffset > 50);
    document.querySelectorAll('.nav-links a').forEach(function (link) {
      var section = document.querySelector(link.getAttribute('href'));
      if (section) {
        var rect = section.getBoundingClientRect();
        link.classList.toggle('active', rect.top <= 150 && rect.bottom >= 150);
      }
    });
  }, { passive: true });

  var carousel = document.getElementById('testimonialCarousel');
  var cards = carousel.querySelectorAll('.testimonial-card');
  var dots = document.querySelectorAll('#testimonialDots .testimonial-dot');
  var prevBtn = document.getElementById('prevTestimonial');
  var nextBtn = document.getElementById('nextTestimonial');
  var currentIndex = 0;
  var autoplayTimer;

  function showTestimonial(index) {
    cards.forEach(function (c, i) {
      c.classList.toggle('active', i === index);
      c.style.transform = i === index ? 'translateX(0) scale(1)' : i < index ? 'translateX(-60px) scale(0.92)' : 'translateX(60px) scale(0.92)';
      c.style.opacity = i === index ? '1' : '0';
    });
    dots.forEach(function (d, i) { d.classList.toggle('active', i === index); });
    currentIndex = index;
  }

  function nextTestimonial() { showTestimonial((currentIndex + 1) % cards.length); }
  function prevTestimonial() { showTestimonial((currentIndex - 1 + cards.length) % cards.length); }
  function startAutoplay() { stopAutoplay(); autoplayTimer = setInterval(nextTestimonial, 5000); }
  function stopAutoplay() { clearInterval(autoplayTimer); }

  prevBtn.addEventListener('click', function () { prevTestimonial(); startAutoplay(); });
  nextBtn.addEventListener('click', function () { nextTestimonial(); startAutoplay(); });
  dots.forEach(function (dot) {
    dot.addEventListener('click', function () {
      showTestimonial(parseInt(dot.dataset.index));
      startAutoplay();
    });
  });

  showTestimonial(0);
  startAutoplay();
</script>
